@requires_node
def test_the_frames_that_were_encoded_are_not_all_full_canvas(film):
    """Why the round trip above is a real test and not a formality.

    `write_gif` passes `optimize=True`, so Pillow writes each frame as the
    *sub-rectangle* that changed, with the rest of it absent. The harness has to honour
    those `left`/`top` offsets and compositing them correctly, and a decoder that
    ignored either would still give the right answer for a GIF written without
    optimization. If Pillow ever stops emitting partial frames this case fails and says
    why, which is the signal that the offsets are no longer covered.
    """
    structure = _gif_structure(film["path"])
    partial = [
        i
        for i, f in enumerate(structure["frames"])
        if (f["left"], f["top"]) != (0, 0)
        or (f["width"], f["height"]) != (structure["width"], structure["height"])
    ]
    assert partial, (
        "every frame is a full canvas, so the round trip is no longer exercising "
        "left/top offsets in the compositor"
    )
    assert any(f["has_local_palette"] for f in structure["frames"]), (
        "no frame carries its own colour table, so the palette branch of decodeGif is "
        "not covered either"
    )


@requires_node
def test_a_wrongly_decoding_page_is_reported_rather_than_passed(page_copy, film, tmp_path):
    """The negative control, without which the round trip proves nothing.

    Two lists of equal length agreeing is also what a decoder that returns zeros
    produces if the reference is wrong too, or if the harness silently emitted nothing.
    So the decoder is sabotaged -- `lzwDecode(...)` replaced by a buffer of zeroes,
    which composites the whole canvas to palette entry 0 -- and the comparison is
    required to notice.
    """
    page = Path(page_copy).read_text(encoding="utf-8")
    needle = "indices: lzwDecode(minCode, stream, w * h)"
    assert page.count(needle) == 1, (
        "the decoder's call site moved, so this case is no longer sabotaging it"
    )
    broken = tmp_path / "broken.html"
    broken.write_text(page.replace(needle, "indices: new Uint8Array(w * h)"), encoding="utf-8")

    report, problems = verify_gif.verify_one(str(broken), film["path"])
    assert problems, "a decoder that returns zeros was declared identical to Pillow"
    assert any("first difference at frame 0" in line for line in problems), problems
    assert report["frames"] == len(report["pillow"]), (
        "the frame count still matches, so this case is proving the hash comparison "
        "rather than the count"
    )


