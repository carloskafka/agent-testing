def test_a_missing_face_names_the_variable_that_overrides_it(monkeypatch, tmp_path):
    """`ImageFont.truetype`'s message names the file, not the way out of it.

    Left alone, a missing font package surfaces as "cannot find resource" from three
    frames deep inside a film, which reads as a broken recording rather than a missing
    dependency. The check is in the loader because that is the only place that can say
    which knob to turn.
    """
    monkeypatch.setenv(build_gifs.FONTDIR_ENV, str(tmp_path))
    build_gifs._fonts.clear()
    try:
        with pytest.raises(OSError) as excinfo:
            build_gifs.F(12)
    finally:
        build_gifs._fonts.clear()
    assert build_gifs.FONTDIR_ENV in str(excinfo.value)
    assert "fonts-dejavu-core" in str(excinfo.value)


@requires_dejavu
def test_f_loads_a_face_through_the_override(monkeypatch, tmp_path):
    """The override has to reach the font *loader*, not just be read back.

    The faces are copied rather than symlinked so the assertion is about which
    directory was opened, and the memo is cleared on both sides because `F` caches on
    `(size, bold, mono)` alone -- an override applied after a face was already loaded
    would otherwise be ignored, which is the one way this could pass vacuously.
    """
    for name in FACES:
        shutil.copy(os.path.join(DEJAVU, name), tmp_path / name)
    monkeypatch.setenv(build_gifs.FONTDIR_ENV, str(tmp_path))
    build_gifs._fonts.clear()
    try:
        face = build_gifs.F(13, bold=True, mono=True)
        assert str(tmp_path) in face.path
        assert face.size == 13
    finally:
        build_gifs._fonts.clear()


@requires_dejavu
def test_a_frame_is_the_size_the_page_lays_out_for():
    """`Frame` is 920x640 because the page's content column is 920 CSS px.

    The size is baked into the player: a frame of different dimensions is stretched by
    the page's own CSS and the type in a recording stops being the type the reader
    would see in the app. `shot` pastes a 908px chat column into an `OUT_W - 12` box, so
    a narrower `OUT_W` would clip it rather than scale it.
    """
    assert build_gifs.Frame("a title", build_gifs.BLUE, tag="t").done().size == (920, 640)
    assert build_gifs.OUT_W - 12 >= 908, "the chat column must fit without scaling"


@requires_dejavu
def test_screenshots_are_cropped_and_never_rescaled(tmp_path):
    """A recording's type has to be the type in the app, so nothing is scaled.

    `region` is documented as a 1:1 crop and `shot_fit` as the deliberate exception.
    The distinction is invisible in the output -- a scaled paste also looks like a
    paste -- so it is asserted on the pixels: `region` puts the source pixels at the
    destination unchanged, and `shot_fit` only ever makes them smaller.
    """
    shot = tmp_path / "shot.png"
    source = Image.new("RGB", (400, 300), (200, 100, 50))
    source.save(shot)

    frame = build_gifs.Frame("crop", build_gifs.BLUE)
    frame.region(str(shot), (0, 0, 40, 30), dst=(100, 200))
    assert frame.img.getpixel((110, 210)) == (200, 100, 50), (
        "region must paste the source pixels, not a resized version of them"
    )

    small = tmp_path / "small.png"
    Image.new("RGB", (40, 30), (200, 100, 50)).save(small)
    frame = build_gifs.Frame("fit", build_gifs.BLUE)
    frame.shot_fit(str(small), (0, 300, 300, 500))
    assert frame.img.getpixel((150, 400)) == (200, 100, 50), "nothing was pasted"
    assert frame.img.getpixel((2, 302)) == build_gifs.BG, (
        "shot_fit must never enlarge: a 40x30 screenshot in a 300x200 box stays 40x30, "
        "centred, and the box keeps its own background around it"
    )

    frame = build_gifs.Frame("fit", build_gifs.BLUE)
    frame.shot_fit(str(shot), (0, 300, 100, 500))
    assert frame.img.getpixel((50, 400)) == (200, 100, 50), (
        "a 400x300 screenshot must be scaled down to fit 100x200"
    )
    assert frame.img.getpixel((50, 320)) == build_gifs.BG, (
        "it fits the width and is centred vertically, so the top of the box is bare"
    )


