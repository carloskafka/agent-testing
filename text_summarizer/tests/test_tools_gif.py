def test_the_icon_colours_come_from_the_light_and_dark_blocks_of_the_page(page_text):
    """The two variants must come from two *different* declarations.

    `token_pair` takes the last match in the slice it is given, and `main` splits the
    stylesheet at the dark-scheme media query -- so the light icon is drawn from the
    `:root` baseline and the dark one from the block that overrides it. If the split
    moved, or if both halves resolved to the same declaration, the generator would
    still succeed and both icons would come out the same colour, which is the one
    outcome the second variant exists to prevent.
    """
    css = page_text[page_text.index("<style>") :]
    dark_at = css.index("@media (prefers-color-scheme: dark)")
    light = make_favicon.token_pair(css[:dark_at])
    dark = make_favicon.token_pair(css[dark_at:])

    for name, pair in (("favicon.svg", light), ("favicon-dark.svg", dark)):
        svg = (DOCS / name).read_text(encoding="utf-8")
        assert f'fill="{pair[0]}"' in svg, f"docs/{name} is not drawn in {pair[0]}"
        assert f'fill="{pair[1]}"' in svg, f"docs/{name} glyph is not {pair[1]}"
    assert light[0] != dark[0] and light[1] != dark[1], (
        "the light and dark variants resolved to the same colours, so one of them is "
        "not being read from the block it is supposed to come from"
    )


