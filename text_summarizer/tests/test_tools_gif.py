    candidates = [
        build_gifs.font_dir(),
        *(
            "/usr/share/fonts/truetype/dejavu",
            "/usr/local/share/fonts/dejavu",
            "/Library/Fonts",
            "/System/Library/Fonts",
        ),
    ]
    for path in candidates:
        if all(os.path.exists(os.path.join(path, name)) for name in FACES):
            return path
    return None


