def test_no_tool_named_in_a_docstring_is_missing():
    """Every `tools/<file>` a reader is told to run has to exist.

    The mistake this pins was in the tree three times: the docstrings in
    `tools/gif_player.js`, `tools/inject_player.py` and `docs/index.html` all named
    `tools/verify_gif.js` for the check that lives in `tools/verify_gif.py` (whose own
    header named a third file, `verify_gif.js_check.py`). Fixed, but the shape of the
    mistake is worth guarding, because it is the one kind of drift no other case in
    this module can see: the decoder check, the favicon check and the player injection
    are all verified, and every docstring explaining how to run them pointed at
    nothing. A docstring is not code, so nothing reads it and nothing fails.

    `docs/index.html` is in the list because it carries a copy of the player's
    comments, so a docstring fix in `gif_player.js` that is not re-injected leaves the
    published page repeating the mistake -- which the byte-identity case above would
    catch for the block as a whole, but not for a reference to a third file.

    The pattern stops at a path segment rather than at the first `.`, because a
    trailing full stop ends the sentence and not the name: the first version of this
    read `tools/make_favicon.py.` and reported a file that does not exist.
    """
    sources = [TOOLS / "gif_player.js", TOOLS / "inject_player.py", TOOLS / "verify_gif.py", PAGE]
    reference = re.compile(r"tools/[\w-]+(?:\.[\w-]+)*")
    missing = []
    for source in sources:
        for name in sorted(set(reference.findall(source.read_text(encoding="utf-8")))):
            if not (REPO_ROOT / name).exists():
                missing.append(f"{source.relative_to(REPO_ROOT)} -> {name}")
    assert not missing, "docstrings name files that are not there: " + "; ".join(missing)


def test_the_guards_referenced_by_the_verifier_actually_exist():
    """`decoder_source`'s error message sends the reader to this file.

    Which means this file has to keep the case that justifies the message, or the
    advice points at a test that is no longer there. Cheap to check, and the failure
    it prevents is the worst kind: a diagnostic that names a path, run by someone
    three months from now, that resolves to nothing.
    """
    message_source = inspect.getsource(verify_gif.decoder_source)
    assert "tests/test_tools_gif.py" in message_source
    assert __file__.endswith("tests/test_tools_gif.py")
    assert "the markers are asserted" not in message_source, (
        "the message still points at an earlier wording of the case below"
    )
