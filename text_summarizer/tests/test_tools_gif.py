def test_the_player_derives_the_gif_from_the_poster_by_a_rule_it_does_not_share(page_text):
    """The rule is read out of the JavaScript rather than restated here.

    `GifPlayer` recovers a recording from its poster with
    `src.replace("-still.png", ".gif")`. Nothing in the build connects that to
    `write_gif`'s `path.replace(".gif", "-still.png")` except the two literals, so a
    poster renamed in the page fetches a URL that does not exist: the figure falls back
    to the native `<img>` and quietly loses every control, with no error anywhere.
    Parsing the rule out of the source means changing it in one place and not the
    other fails here.
    """
    player = (TOOLS / "gif_player.js").read_text(encoding="utf-8")
    rule = re.search(
        r'\(\s*this\.poster\.getAttribute\("src"\)\s*\|\|\s*""\s*\)\s*'
        r'\.replace\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)',
        player,
    )
    assert rule, "the poster src is no longer turned into a gif by a .replace()"
    needle, replacement = rule.group(1), rule.group(2)
    assert (needle, replacement) == ("-still.png", ".gif"), (
        f"the player now maps {needle!r} -> {replacement!r}; the build that writes "
        "those names and the page that refers to them need reconciling"
    )

    posters = re.findall(r'<img src="([^"]*-still\.png)"', page_text)
    assert posters, "no posters on the page, so the derived URL rule is not exercised"
    for poster in posters:
        derived = poster.replace(needle, replacement)
        assert (DOCS / derived).is_file(), (
            f"the player would fetch {derived} from the poster {poster}, and there is "
            "no such file: the figure would lose its transport and show the poster "
            "forever"
        )


def test_the_still_naming_rule_and_the_players_rule_are_inverses(encoded):
    """What the build writes is exactly what the player expects to read.

    `write_gif` derives the poster from the recording's own path, so the two halves
    only agree if the substitution round-trips for the names the build actually
    produces. The recordings are named after whatever film they are (`e2e-main.gif`,
    `e2e-gmail.gif`), so a rule that only works for one of them is enough to break the
    page -- which is why this is checked on a name the writer derived rather than on a
    hand-written one.
    """
    poster = encoded["still"].name
    assert poster == "e2e-some-recording-still.png"
    assert poster.replace("-still.png", ".gif") == "e2e-some-recording.gif"
    assert "e2e-some-recording.gif".replace(".gif", "-still.png") == poster
    assert encoded["still"].is_file(), (
        "the poster was not written where the player's rule says to look for it"
    )
    # And a sibling of the recording, not a file the page resolves some other way: the
    # src in the page is a plain relative path next to it.
    assert encoded["still"].parent == encoded["merged"].parent


