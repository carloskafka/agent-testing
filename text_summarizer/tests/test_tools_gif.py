def test_distinct_drops_a_frame_that_moved_too_little_to_be_worth_playing(tmp_path):
    """The stated purpose: a progress bar ticking is not a scene change.

    Played at 190ms each, near-identical frames pad the loop and make a 40s turn feel
    longer than it was. A capture that is genuinely idle -- which `capture_ui.py`'s
    own `shoot()` avoids by comparing raw bytes, but which a stalled browser or a
    pending keyframe still produces -- has to collapse.
    """
    caps = _capture(
        tmp_path,
        [
            _rgb_field(size=(3, 3)),  # a dot, not a scene
            _rgb_field(size=(4, 4)),
            _rgb_field(size=(400, 300)),
        ],
    )  # a panel
    assert caps.distinct() == [0, 2], (
        "frame 1 changed a 3x3 dot, which is 9 pixels of 17760 after the thumbnail "
        "-- far under the 2% threshold, so it is padding"
    )


def test_distinct_keeps_a_frame_where_the_screen_actually_moved(tmp_path):
    """The other half: a generous threshold must not throw the content away."""
    frames = [_rgb_field(size=(200 + 200 * i, 300)) for i in range(4)]
    assert _capture(tmp_path, frames).distinct() == [0, 1, 2, 3]


def test_distinct_always_keeps_the_first_frame(tmp_path):
    """A recording that never changes still has to show something.

    `prev` is None on the first frame, so the threshold cannot be applied to anything
    and the frame is kept unconditionally. Without that, a static capture would encode
    to zero frames and `write_gif` would then fail on `quants[0]` -- an IndexError a
    long way from its cause.
    """
    assert _capture(tmp_path, [_rgb_field()]).distinct() == [0]


def test_a_capture_that_never_moves_collapses_to_one_frame(tmp_path):
    """The pathological recording, which is the case the method exists for."""
    caps = _capture(tmp_path, [_rgb_field() for _ in range(30)])
    assert len(caps) == 30
    assert caps.distinct() == [0]


def test_distinct_compares_against_the_last_kept_frame_not_the_previous_one(tmp_path):
    """`prev` only moves when a frame is kept, so a repeat of frame 0 is dropped.

    In `A, A', A` the near-duplicate is dropped *and* the exact repeat after it, because
    the thing being compared against is still A. The consequence is that a capture
    which oscillates does not collapse -- `A, B, A` keeps all three, since each A is
    compared against the B the reader last saw. That is the behaviour to know about
    before replacing it with a "have I seen this frame before?" set, which would
    freeze a legitimately repeating animation on its first pass.
    """
    a = _rgb_field(size=(400, 300))
    a_prime = _rgb_field(size=(400, 300), at=(101, 100))
    b = _rgb_field(size=(400, 300), at=(600, 400))
    assert _capture(tmp_path, [a, a_prime, a]).distinct() == [0]
    assert _capture(tmp_path, [a, b, a]).distinct() == [0, 1, 2]


def test_distinct_is_luminance_only_so_a_pure_hue_change_is_invisible(tmp_path):
    """The thumbnail is greyscale, so two very different frames can look equal.

    `(255,0,0)` and `(0,130,0)` both have luminance 76, so a frame that repaints a
    large area from one to the other produces an *identical* greyscale thumbnail and
    is dropped -- even though the RGB bytes differ across a third of the frame.
    Nothing in the walkthroughs changes only hue, so this is not a live bug; it is
    pinned because it is the assumption that would be quietly wrong if the comparison
    were ever ported to a perceptual metric, and because whoever does that port should
    find out here that the 2% threshold was chosen against greyscale.
    """
    red = _rgb_field(block=(255, 0, 0), size=(500, 500))
    green = _rgb_field(block=(0, 130, 0), size=(500, 500))
    assert red.convert("L").getpixel((300, 300)) == green.convert("L").getpixel((300, 300)) == 76
    assert red.tobytes() != green.tobytes(), "the frames must differ in RGB for this to bite at all"
    assert _capture(tmp_path, [red, green]).distinct() == [0]


def test_a_zero_threshold_keeps_every_frame(tmp_path):
    """`threshold=0.0` is the "do not drop anything" setting, and it has to mean it.

    The comparison is a strict `<`, so a threshold of zero can never be met and every
    frame is kept. Worth pinning because the alternative -- `<=` -- would still drop
    exact duplicates at 0.0, which is not what asking for no threshold is asking for.
    """
    caps = _capture(tmp_path, [_rgb_field() for _ in range(4)])
    assert caps.distinct(threshold=0.0) == [0, 1, 2, 3]


