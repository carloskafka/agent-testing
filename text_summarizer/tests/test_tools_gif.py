    assert Path(page_copy).read_bytes() == PAGE.read_bytes(), (
        "re-running tools/inject_player.py changes docs/index.html -- the player block "
        "in the page is not the current tools/gif_player.js. Re-run it and commit the "
        "result."
    )
    assert hashlib.sha256(PAGE.read_bytes()).hexdigest() == before, (
        "the real docs/index.html was modified by the test"
    )


