"""The walkthrough pipeline's own contract, tested offline.

`tools/` is ~3,200 lines that record the agent and produce the published site,
and until now nothing tested any of it. That is not a tidiness complaint. The
pipeline has three properties that fail *silently*, and all three were found
while writing this module:

* **`tools/verify_gif.py` had never run.** Its node harness had
  ``const body = block.slice(body.indexOf('(function ()'));`` -- a binding named
  inside its own initializer, which is a `ReferenceError` under the temporal dead
  zone. So the tool whose entire job is to prove the inlined decoder reproduces
  Pillow aborted on line 7, before printing anything, and no eyeball would have
  caught it, because the failure lives in a subprocess whose stderr nobody reads.
  The decoder it was meant to check turns out to be correct -- all three checked-in
  recordings do match Pillow -- but that fact had never been established by
  anything. Hence `test_the_harness_never_names_a_binding_it_is_defining`, which
  needs no `node` and must never be skipped for want of one, and hence the round
  trip below, which does.

* **The generated artifacts have no generator-side check.** `docs/index.html` is
  generated (the player block is `tools/gif_player.js`, inlined by
  `tools/inject_player.py`) and `docs/favicon*.svg|png` are generated by
  `tools/make_favicon.py`. Both are checked in, neither was verified. A stale
  player means the published page runs a decoder that was never checked; a stale
  icon means the tab shows a colour the page stopped using. Both are re-derived
  here and compared -- in `tmp_path`, because this suite has no business rewriting
  the site as a side effect of asserting that it is up to date.

* **The player's URL is derived by string surgery.** `gif_player.js` recovers a
  recording from its poster with `src.replace("-still.png", ".gif")`, and the
  poster is what `write_gif` wrote with `path.replace(".gif", "-still.png")`.
  Nothing connects the two halves except the two literals, so a poster renamed in
  the page 404s the recording on a deployed site, with no build step in between to
  catch it. The rule is read out of the JavaScript rather than restated here, so
  changing it in one place and not the other fails.

Everything here is offline: frames are generated, fonts are found or skipped, and
`node` is used when present and skipped with a stated reason when not. Nothing
starts a browser, a container, or a turn.

Conventions: the modules under `tools/` are standalone scripts, not a package, so
they are loaded by path the way `test_adk_devui_patch.py` loads
`patch-adk-devui-mobile.py` -- no `sys.path` surgery, and no chance of the import
shadowing a real module name.

Two of the measurements below read the encoded bytes rather than asking Pillow to
decode them (`_gif_structure`, `_channel_error`). That is deliberate: Pillow's
decode API resolves colour tables and frame offsets before you can see them, and
the properties being asserted -- *one* palette for the whole file, *partial*
frames -- are properties of what the encoder wrote. Measuring them through the
decoder would mean measuring the decoder's opinion of them.
"""

