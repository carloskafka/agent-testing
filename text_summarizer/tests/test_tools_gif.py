def _scene(index: int, total: int) -> Image.Image:
    """A frame with plenty of distinct colours and a visible label.

    The colour count is load-bearing rather than decorative: `write_gif` builds one
    shared palette out of at most 12 frames, so frames that each carry their own
    hundreds of colours are what make that palette observable in the output.
    """
    img = Image.new("RGB", (build_gifs.OUT_W, build_gifs.OUT_H), (10, 12, 16))
    d = ImageDraw.Draw(img)
    d.rectangle((0, 0, build_gifs.OUT_W, build_gifs.BAR), fill=(21, 26, 33))
    for k in range(40):
        d.rectangle(
            (6 + k * 22, 40 + (k % 8) * 60, 6 + k * 22 + 18, 90 + (k % 8) * 60),
            fill=(
                (index * 53 + k * 11) % 256,
                (index * 17 + k * 43) % 256,
                (index * 97 + k * 29) % 256,
            ),
        )
    d.rectangle((40, 540, 40 + 24 * (index + 1), 560), fill=(124, 178, 255))
    d.text((12, build_gifs.BAR // 2), f"scene {index + 1}/{total}", fill=(231, 236, 242))
    return img


def _capture(root: Path, frames: list[Image.Image], name: str = "live") -> build_gifs.Captures:
    """A `capture_ui.py` output directory, synthesised.

    `Captures` reads exactly two things -- `index.json` (`prompt`, plus `frames`
    with `file` and `t`) and the PNGs it points at -- so to every consumer in
    `build_gifs.py` this is a real capture, produced without a browser, a Marionette
    socket or a spent API key. The frames are `capture_ui.py`'s own size, 1400x900.
    """
    directory = root / name
    directory.mkdir(parents=True, exist_ok=True)
    index = {"prompt": "Summarize: something not in the vault yet", "frames": []}
    for i, img in enumerate(frames):
        filename = f"{name}-{i:03d}-frame.png"
        img.save(directory / filename)
        index["frames"].append({"file": filename, "t": round(i * 1.5, 2)})
    (directory / "index.json").write_text(json.dumps(index), encoding="utf-8")
    return build_gifs.Captures(str(root), name)


def _rgb_field(
    block=(255, 0, 0), size=(100, 100), at=(100, 100), background=(0, 0, 0)
) -> Image.Image:
    """A mostly-black 1400x900 frame with one solid block in it."""
    img = Image.new("RGB", (1400, 900), background)
    ImageDraw.Draw(img).rectangle((at[0], at[1], at[0] + size[0], at[1] + size[1]), fill=block)
    return img


# --- reading what the encoder wrote --------------------------------------------


def _gif_structure(path) -> dict:
    """The GIF's block structure: geometry, colour tables, frame rectangles.

    Pillow's decode API resolves all of this before a caller can see it -- a frame
    that is a sub-rectangle comes back as a full canvas, and a frame with its own
    colour table comes back with one shared palette attached. So the two properties
    this module wants to assert about `write_gif`'s output -- one palette for the
    file, frames that are only as large as what changed -- are properties of the
    *bytes*, and reading them back through a decoder would mean measuring the
    decoder's opinion instead.

    A GIF is: header, logical screen descriptor, optional global colour table,
    then a sequence of extension / image-descriptor / trailer blocks. Image
    descriptors carry their own optional colour table, then one LZW minimum-code-size
    byte, then the length-prefixed pixel sub-blocks. Anything this parser does not
    recognise ends the walk rather than raising, which is why the tests below also
    assert the frame count came out right.
    """
    raw = Path(path).read_bytes()
    if raw[:3] != b"GIF":
        raise AssertionError(f"{path} is not a GIF")
    width, height = struct.unpack_from("<HH", raw, 6)
    packed = raw[10]
    p = 13
    global_table = None
    if packed & 0x80:
        size = 1 << ((packed & 7) + 1)
        global_table = [tuple(raw[p + 3 * i : p + 3 * i + 3]) for i in range(size)]
        p += 3 * size

    frames = []
    while p < len(raw):
        block = raw[p]
        p += 1
        if block == 0x3B:  # trailer
            break
        if block == 0x21:  # extension
            p += 1  # the label
            if raw[p] == 0xF9:  # graphic control
                p += 1 + raw[p]  # size byte + fixed fields
            while raw[p]:  # sub-blocks
                p += 1 + raw[p]
            p += 1
            continue
        if block != 0x2C:  # not an image descriptor
            break
        left, top, w, h = struct.unpack_from("<HHHH", raw, p)
        p += 8
        ipacked = raw[p]
        p += 1
        local = None
        if ipacked & 0x80:
            size = 1 << ((ipacked & 7) + 1)
            local = [tuple(raw[p + 3 * i : p + 3 * i + 3]) for i in range(size)]
            p += 3 * size
        p += 1  # LZW minimum code size
        while raw[p]:
            p += 1 + raw[p]
        p += 1
        frames.append(
            {
                "left": left,
                "top": top,
                "width": w,
                "height": h,
                "palette": local or global_table,
                "has_local_palette": local is not None,
            }
        )
    return {"width": width, "height": height, "global_palette": global_table, "frames": frames}


def _channel_error(sources: list[Image.Image], gif_path) -> tuple[float, int, int]:
    """``(mean, 99.9th percentile, worst)`` absolute per-channel error.

    Vectorised through `ImageChops` and per-band histograms, because the obvious
    `zip(a, b)` over 1.76M bytes per frame is 42M Python iterations and turns a
    sub-second check into a fifteen-second one. The percentiles are reported rather
    than a bare maximum because a handful of antialiased glyph edges against a
    255-colour palette is expected and invisible, while a *shifted* palette moves
    the mean -- which is the failure that matters.
    """
    total = 0
    count = 0
    pooled = [0] * 256
    im = Image.open(gif_path)
    for i, source in enumerate(sources):
        im.seek(i)
        for band in ImageChops.difference(source, im.convert("RGB")).split():
            histogram = band.histogram()
            pooled = [a + b for a, b in zip(pooled, histogram, strict=True)]
            total += sum(level * n for level, n in enumerate(histogram))
            count += sum(histogram)
    everything = sum(pooled)
    seen = 0
    percentile = 0
    for level, n in enumerate(pooled):
        seen += n
        if seen >= 0.999 * everything:
            percentile = level
            break
    worst = max(level for level, n in enumerate(pooled) if n)
    return total / count, percentile, worst


