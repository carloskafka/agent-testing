def test_write_gif_reports_what_main_prints(film):
    """`main` formats `frames`, `ms` and `bytes` from this dict and nothing else.

    A renamed key is a `KeyError` at the end of a build that has already spent a
    real recording, so the contract is pinned where it is produced.
    """
    assert set(film["info"]) == {"frames", "ms", "bytes"}
    assert film["info"]["frames"] == len(film["frames"])
    assert film["info"]["ms"] == sum(ms for _, ms in film["frames"])
    assert film["info"]["bytes"] == os.path.getsize(film["path"])


def test_write_gif_merges_consecutive_identical_frames_and_adds_their_time(encoded):
    """The reason the merge exists: a pause must cost one frame of bytes.

    A recording holds on a scene while nothing moves, and `hold()` already collapses
    those into single frames -- but `films.py` stitches several scenes together, so an
    identical frame can also land at a scene boundary. Merging changes nothing a reader
    sees and can halve a file. The durations have to add, or the merge is not free: the
    scene would play faster than it was recorded.
    """
    structure = _gif_structure(encoded["merged"])
    assert len(structure["frames"]) == 7, (
        "the two extra a's and the two extra c's should have merged, and the a b a b "
        "tail should have survived: 9 frames in, 7 out"
    )

    durations = []
    im = Image.open(encoded["merged"])
    for i in range(im.n_frames):
        im.seek(i)
        durations.append(im.info.get("duration"))
    assert durations == [500, 100, 600, 100, 100, 100, 100], (
        "merged frames keep their total on-screen time"
    )


def test_write_gif_merges_only_consecutive_duplicates(encoded):
    """`a, b, a` stays three frames, and the file still says so in its pixels.

    The merge compares against the *last emitted* frame only, so a scene that returns
    to an earlier look does not collapse into it. A naive "drop any repeated frame"
    pass would get this wrong, and it is what keeps a loop that revisits a panel from
    losing the revisit. The last four frames of the same encode are `a b a b`, and
    frames 3 and 5 must be the *same picture* -- checked on the pixels rather than on
    a count, because a count alone cannot tell a preserved repeat from a reshuffle.
    """
    im = Image.open(encoded["merged"])
    pixels = []
    for i in range(im.n_frames):
        im.seek(i)
        pixels.append(im.convert("RGB").tobytes())
    assert len(pixels) == 7
    assert pixels[3] == pixels[5], "frames 3 and 5 are the same source frame"
    assert pixels[4] == pixels[6], "frames 4 and 6 are the same source frame"
    assert pixels[3] != pixels[4], "and they are not all the same picture"


def test_every_frame_is_quantized_against_one_shared_palette(film):
    """The montage's whole purpose: one palette for the file, not one per frame.

    Without it every frame would be quantized on its own, so the union of colours
    across the recording would grow with the frame count and two adjacent frames
    could disagree about a colour they share -- which is what a palette shift
    between two frames of the same panel looks like. Pillow writes each frame's
    palette into the frame itself, so the checkable form of "one palette" is that
    every colour table in the file is a subset of the single global one. A
    per-frame quantize breaks exactly that.
    """
    structure = _gif_structure(film["path"])
    assert structure["global_palette"], "the file has no global colour table at all"

    tables = [set(f["palette"]) for f in structure["frames"]]
    global_table = set(structure["global_palette"])
    stray = [i for i, table in enumerate(tables) if not table <= global_table]
    assert not stray, (
        f"frames {stray[:5]} carry colours that are not in the shared palette, so "
        "they were not quantized against the montage"
    )
    # Teeth: without this, a file whose frames happen to use four colours each would
    # pass the subset check whatever the encoder did.
    assert sum(len(t) for t in tables) > 255, (
        "the frames carry fewer colours in total than one palette holds, so the "
        "shared-palette property is not actually being tested"
    )
    # 255 entries rounded up to the next power of two on the way out; `quantize` is
    # what cannot ask for more than 255, and it is `write_gif` that asks.
    assert len(global_table) <= 256


def test_the_written_frames_still_look_like_the_frames_that_went_in(film):
    """A 255-colour palette is a lossy step, and the size of the loss is pinned.

    Quantizing is not free, so a regression that made the montage palette much worse
    would show up as poster-quality output rather than as a failing check -- which is
    why the bound is asserted rather than assumed. The mean is the meaningful number
    (measured here at 0.64 of a level per channel: invisible); the 99.9th percentile
    is the guard against a palette that is merely unlucky on one antialiased glyph
    edge. A *shifted* palette moves the mean, not the tail.
    """
    mean, percentile, worst = _channel_error([img for img, _ in film["frames"]], film["path"])
    assert mean < 4.0, f"mean channel error {mean:.2f} is visible banding"
    assert percentile <= 64, (
        f"the 99.9th percentile is {percentile} levels out of 255 (worst single pixel: {worst})"
    )


def test_the_still_is_the_frame_that_was_asked_for_at_full_size(film):
    """`still=-1` -- what every film in `films.py` asks for -- is the last frame.

    The poster is what a `prefers-reduced-motion` reader sees for good, so it has to
    be a frame of the recording rather than a thumbnail of one, and it has to be the
    frame the film named. It is written from the *quantized* image, so it is compared
    against Pillow's own decode of that frame: if the two ever diverged, the still
    would be showing colours the GIF itself cannot produce.
    """
    assert film["still"].is_file(), f"expected the still beside the gif: {film['still']}"
    still = Image.open(film["still"]).convert("RGB")
    assert still.size == (build_gifs.OUT_W, build_gifs.OUT_H), (
        "a half-size still is visibly soft at the width of the stage on a HiDPI "
        "screen -- the comment above write_gif's still branch says so"
    )

    im = Image.open(film["path"])
    im.seek(im.n_frames - 1)
    assert still.tobytes() == im.convert("RGB").tobytes()


def test_the_still_index_is_honoured_wherever_it_points(encoded):
    """`still=0` writes frame 0, not the last frame -- which is the whole point.

    Every film in `films.py` currently asks for `-1`, so an implementation that ignored
    the argument entirely would pass every one of them. The still is chosen by the
    film, and a film that chooses an earlier frame -- the prompt, before anything has
    happened -- is a reasonable thing to write, which is why the index is pinned
    against a file of seven frames and a request for the first.
    """
    im = Image.open(encoded["merged"])
    first = Image.open(encoded["still"]).convert("RGB").tobytes()

    im.seek(0)
    assert first == im.convert("RGB").tobytes()
    im.seek(2)
    assert first != im.convert("RGB").tobytes(), "it is not frame 2 either"
    im.seek(im.n_frames - 1)
    assert first != im.convert("RGB").tobytes(), "and it is not the last frame"


def test_no_still_is_written_unless_one_is_asked_for(encoded):
    """`build_films` may omit the key, and a stray -still.png would go stale.

    A poster left behind from an earlier build is worse than no poster: the page
    prefers it for a reduced-motion reader, so it would show a frame from a recording
    that no longer exists, and nothing in the build would notice.
    """
    assert encoded["bare"].is_file()
    assert not encoded["bare"].with_name("bare-still.png").exists()


